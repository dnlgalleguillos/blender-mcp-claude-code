routes: dict = {}
seen: list = []


def route(method: str, prefix: str, response):
    """Answer requests to URLs starting with prefix. A fixed response is copied for every request."""
    if callable(response):
        routes[(method, prefix)] = response
    else:
        routes[(method, prefix)] = lambda req, r=response: httpx.Response(
            r.status_code, content=r.content, headers={k: v for k, v in r.headers.items() if k.lower() not in ("content-length", "content-encoding")})


def handler(request: httpx.Request) -> httpx.Response:
    seen.append(request)
    url = str(request.url)
    best = None
    for (method, prefix), fn in routes.items():
        if request.method == method and url.startswith(prefix) and (best is None or len(prefix) > len(best[0])):
            best = (prefix, fn)
    return best[1](request) if best else httpx.Response(599, text="no route for " + url)


def factory(**kw):
    return httpx.AsyncClient(transport=httpx.MockTransport(handler), **kw)


def ok(js=None, content=None, **kw):
    return httpx.Response(200, json=js, **kw) if js is not None else httpx.Response(200, content=content or b"", **kw)


def calls(prefix: str):
    return [r for r in seen if str(r.url).startswith(prefix)]


